-- Helpdesk ticketing schema used by the frontend (src/api/tickets.js).
-- The older public.tasks table is left untouched.

create type public.ticket_status as enum ('open', 'in_progress', 'pending', 'resolved', 'closed');
create type public.ticket_priority as enum ('low', 'medium', 'high', 'urgent');
create type public.agent_presence as enum ('online', 'away', 'offline');

create table public.agents (
  id        text primary key,
  name      text not null check (char_length(btrim(name)) between 1 and 120),
  email     text not null unique,
  role      text not null,
  team      text not null,
  presence  public.agent_presence not null default 'offline',
  csat      int not null default 0 check (csat between 0 and 100)
);

create table public.customers (
  id        text primary key,
  name      text not null check (char_length(btrim(name)) between 1 and 120),
  email     text not null unique,
  company   text not null,
  plan      text not null check (plan in ('Starter', 'Business', 'Enterprise')),
  location  text
);

-- Tickets are shown as TCK-<number>; numbers start above the seeded range.
create table public.tickets (
  number             bigint generated by default as identity (start with 1100) primary key,
  subject            text not null check (char_length(btrim(subject)) between 1 and 200),
  status             public.ticket_status not null default 'open',
  priority           public.ticket_priority not null default 'medium',
  category           text not null check (category in ('Technical', 'Billing', 'Account', 'Bug report', 'Feature request')),
  channel            text not null check (channel in ('email', 'chat', 'phone', 'web')),
  customer_id        text not null references public.customers (id),
  assignee_id        text references public.agents (id) on delete set null,
  tags               text[] not null default '{}',
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  first_response_at  timestamptz
);

create index tickets_updated_at_idx on public.tickets (updated_at desc);
create index tickets_assignee_idx on public.tickets (assignee_id) where assignee_id is not null;
create index tickets_customer_idx on public.tickets (customer_id);

-- author_id points at customers.id or agents.id depending on author.
create table public.ticket_messages (
  id          bigint generated always as identity primary key,
  ticket_no   bigint not null references public.tickets (number) on delete cascade,
  author      text not null check (author in ('customer', 'agent')),
  author_id   text not null,
  body        text not null check (char_length(btrim(body)) between 1 and 5000),
  internal    boolean not null default false,
  created_at  timestamptz not null default now()
);

create index ticket_messages_ticket_idx on public.ticket_messages (ticket_no, created_at);

create table public.ticket_activity (
  id          bigint generated always as identity primary key,
  ticket_no   bigint not null references public.tickets (number) on delete cascade,
  text        text not null,
  created_at  timestamptz not null default now()
);

create index ticket_activity_ticket_idx on public.ticket_activity (ticket_no, created_at);

-- Demo mode, same as public.tasks: no login, so anon may read and write.
-- Replace these policies once Supabase Auth is added.
do $$
declare t text;
begin
  foreach t in array array['agents', 'customers', 'tickets', 'ticket_messages', 'ticket_activity'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "public read" on public.%I for select to anon, authenticated using (true)', t);
    execute format('grant select on public.%I to anon, authenticated', t);
  end loop;
  foreach t in array array['tickets', 'ticket_messages', 'ticket_activity'] loop
    execute format('create policy "public insert" on public.%I for insert to anon, authenticated with check (true)', t);
    execute format('grant insert on public.%I to anon, authenticated', t);
  end loop;
end $$;

-- Messages and activity are an append-only history: only tickets can be updated.
create policy "public update" on public.tickets for update to anon, authenticated using (true) with check (true);
grant update on public.tickets to anon, authenticated;
